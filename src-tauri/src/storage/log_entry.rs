use std::collections::VecDeque;
use std::net::IpAddr;
use std::time::SystemTime;

#[derive(Debug, Clone)]
pub enum LogEntry {
    ARP {
        npid: String,
        parent: String,
        timestamp: SystemTime,
        protocol: String,
        source: String,
        destination: String,
        length: usize,
        info: String,
        interface: String,
        payload: Vec<u8>,
        hardware_type: u16,
        protocol_type: u16,
        hardware_addr_length: u8,
        protocol_addr_length: u8,
        operation: u16,
        sender_hw_addr: String,
        sender_proto_addr: String,
        target_hw_addr: String,
        target_proto_addr: String,
    },
    DNS {
        npid: String,
        parent: String,
        timestamp: SystemTime,
        protocol: String,
        source: String,
        destination: String,
        length: usize,
        info: String,
        interface: String,
        header: String,
        queries: Vec<String>,
        answers: Vec<String>,
        name_servers: Vec<String>,
        additionals: Vec<String>,
        signature: String,
        edns: Option<String>,
    },
    Ethernet {
        npid: String,
        parent: String,
        timestamp: SystemTime,
        protocol: String,
        source: String,
        destination: String,
        length: usize,
        info: String,
        interface: String,
        payload: Vec<u8>,
        ethernet_type: u16,
    },
    ICMP {
        npid: String,
        parent: String,
        timestamp: SystemTime,
        protocol: String,
        source: String,
        destination: String,
        length: usize,
        info: String,
        interface: String,
        payload: Vec<u8>,
        icmp_type: u8,
        icmp_code: u8,
        checksum: u16,
    },
    ICMPv6 {
        npid: String,
        parent: String,
        timestamp: SystemTime,
        protocol: String,
        source: String,
        destination: String,
        length: usize,
        info: String,
        interface: String,
        payload: Vec<u8>,
        icmpv6_type: u8,
        icmpv6_code: u8,
        checksum: u16,
        identifier: u16,
        sequence_number: u16,
    },
    IPv4 {
        npid: String,
        parent: String,
        timestamp: SystemTime,
        protocol: String,
        source: String,
        destination: String,
        length: usize,
        info: String,
        interface: String,
        payload: Vec<u8>,
        version: u8,
        header_length: u8,
        dscp: u8,
        ecn: u8,
        total_length: u16,
        identification: u16,
        flags: u8,
        fragment_offset: u16,
        ttl: u8,
        next_level_protocol: u8,
        checksum: u16,
        source_ip: String,
        destination_ip: String,
        options: VecDeque<u8>,
    },
    IPv6 {
        npid: String,
        parent: String,
        timestamp: SystemTime,
        protocol: String,
        source: String,
        destination: String,
        length: usize,
        info: String,
        interface: String,
        payload: Vec<u8>,
        version: u8,
        traffic_class: u8,
        flow_label: u32,
        payload_length: u16,
        next_header: u8,
        hop_limit: u8,
        source_ip: String,
        destination_ip: String,
    },
    TCP {
        npid: String,
        parent: String,
        timestamp: SystemTime,
        protocol: String,
        source: String,
        destination: String,
        length: usize,
        info: String,
        interface: String,
        payload: Vec<u8>,
        tcp_source: u16,
        tcp_destination: u16,
        sequence_number: u32,
        acknowledgment_number: u32,
        data_offset: u8,
        reserved: u8,
        flags: u8,
        window: u16,
        checksum: u16,
        urgent_pointer: u16,
        options: VecDeque<u8>,
    },
    UDP {
        npid: String,
        parent: String,
        timestamp: SystemTime,
        protocol: String,
        source: String,
        destination: String,
        length: usize,
        info: String,
        interface: String,
        payload: Vec<u8>,
        udp_source: u16,
        udp_destination: u16,
        length_udp: u16,
        checksum: u16,
    },
    Other {
        npid: String,
        parent: String,
        timestamp: SystemTime,
        protocol: String,
        source: String,
        destination: String,
        length: usize,
        info: String,
        interface: String,
        payload: Vec<u8>,
    },
}
